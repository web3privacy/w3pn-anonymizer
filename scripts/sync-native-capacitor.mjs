import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const distDir = resolve(root, 'dist')
const iosPublicDir = resolve(root, 'ios/App/App/public')
const iosConfigPath = resolve(root, 'ios/App/App/capacitor.config.json')
const iosCordovaConfigPath = resolve(root, 'ios/App/App/config.xml')
const iosSpmVendorDir = resolve(root, 'ios/App/CapApp-SPM/Vendor')
const androidAssetsDir = resolve(root, 'android/app/src/main/assets')
const androidPublicDir = resolve(androidAssetsDir, 'public')
const androidConfigPath = resolve(androidAssetsDir, 'capacitor.config.json')
const androidPluginsPath = resolve(androidAssetsDir, 'capacitor.plugins.json')
const androidCordovaDir = resolve(root, 'android/capacitor-cordova-android-plugins')
const androidCordovaBuildPath = resolve(androidCordovaDir, 'build.gradle')
const androidCordovaVariablesPath = resolve(androidCordovaDir, 'cordova.variables.gradle')
const cordovaTemplatePath = resolve(root, 'node_modules/@capacitor/cli/assets/capacitor-cordova-android-plugins.tar.gz')

const IOS_FRAMEWORKS = [
  {
    name: 'Capacitor',
    url: 'https://github.com/ionic-team/capacitor-swift-pm/releases/download/7.6.7/Capacitor.xcframework.zip',
    checksum: '31f0456603ddc775fe2f3df8dc65b58fb0bb79dca9f7650791c829ce2fee33ff',
  },
  {
    name: 'Cordova',
    url: 'https://github.com/ionic-team/capacitor-swift-pm/releases/download/7.6.7/Cordova.xcframework.zip',
    checksum: '1452a74ca23d2fc670a881705bf3b56491e9ec31271fefe129ca6f602c32e675',
  },
]

if (!existsSync(resolve(distDir, 'index.html'))) {
  throw new Error('Missing dist/index.html. Run npm run build before syncing native apps.')
}

const nativeConfig = {
  appId: 'info.web3privacy.anonymizer',
  appName: 'W3PN Anonymizer',
  webDir: 'public',
  bundledWebRuntime: false,
  server: {
    androidScheme: 'https',
  },
  backgroundColor: '#000000',
  ios: {
    contentInset: 'never',
    backgroundColor: '#000000',
  },
}

function syncPublicAssets(targetDir) {
  mkdirSync(targetDir, { recursive: true })
  rmSync(targetDir, { recursive: true, force: true })
  cpSync(distDir, targetDir, { recursive: true })
  pruneMacJunk(targetDir)
}

function pruneMacJunk(dir) {
  for (const entry of readdirSync(dir)) {
    const path = resolve(dir, entry)
    if (entry === '.DS_Store') {
      rmSync(path, { force: true })
      continue
    }
    if (statSync(path).isDirectory()) pruneMacJunk(path)
  }
}

function ensureAndroidCordovaModule() {
  if (!existsSync(resolve(androidCordovaDir, 'build.gradle'))) {
    mkdirSync(androidCordovaDir, { recursive: true })
    execFileSync('tar', ['-xzf', cordovaTemplatePath, '-C', androidCordovaDir], { stdio: 'inherit' })
  }

  let buildGradle = readFileSync(androidCordovaBuildPath, 'utf8')
  if (!buildGradle.includes("apply from: 'cordova.variables.gradle'")) {
    buildGradle = buildGradle.replace(
      "apply plugin: 'com.android.library'",
      "apply plugin: 'com.android.library'\napply from: 'cordova.variables.gradle'",
    )
    writeFileSync(androidCordovaBuildPath, buildGradle)
  }

  writeFileSync(
    androidCordovaVariablesPath,
    `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
ext {
  cdvMinSdkVersion = project.hasProperty('minSdkVersion') ? rootProject.ext.minSdkVersion : 23
  cdvPluginPostBuildExtras = []
  cordovaConfig = [:]
}
`,
  )
}

function ensureIosSpmVendorFrameworks() {
  mkdirSync(iosSpmVendorDir, { recursive: true })

  for (const framework of IOS_FRAMEWORKS) {
    const frameworkDir = resolve(iosSpmVendorDir, `${framework.name}.xcframework`)
    if (existsSync(resolve(frameworkDir, 'Info.plist'))) continue

    const zipPath = resolve(root, `.native-cache/${framework.name}.xcframework.zip`)
    mkdirSync(resolve(root, '.native-cache'), { recursive: true })
    execFileSync('curl', ['-L', '--fail', '--output', zipPath, framework.url], { stdio: 'inherit' })

    const actual = execFileSync('swift', ['package', 'compute-checksum', zipPath], { encoding: 'utf8' }).trim()
    if (actual !== framework.checksum) {
      throw new Error(`${framework.name}.xcframework checksum mismatch. Expected ${framework.checksum}, got ${actual}.`)
    }

    rmSync(frameworkDir, { recursive: true, force: true })
    execFileSync('unzip', ['-q', zipPath, '-d', iosSpmVendorDir], { stdio: 'inherit' })
    pruneMacJunk(frameworkDir)
  }

  sanitizeIosVendorFrameworks()
}

function sanitizeIosVendorFrameworks() {
  for (const framework of IOS_FRAMEWORKS) {
    const frameworkDir = resolve(iosSpmVendorDir, `${framework.name}.xcframework`)
    if (!existsSync(resolve(frameworkDir, 'Info.plist'))) continue

    const cleanDir = resolve(root, `.native-cache/${framework.name}.xcframework.clean`)
    rmSync(cleanDir, { recursive: true, force: true })
    execFileSync('ditto', ['--norsrc', frameworkDir, cleanDir], { stdio: 'inherit' })
    rmSync(frameworkDir, { recursive: true, force: true })
    renameSync(cleanDir, frameworkDir)
    pruneMacJunk(frameworkDir)
  }
}

syncPublicAssets(iosPublicDir)
writeFileSync(iosConfigPath, `${JSON.stringify(nativeConfig, null, 2)}\n`)
writeFileSync(
  iosCordovaConfigPath,
  `<?xml version="1.0" encoding="UTF-8"?>
<widget xmlns="http://www.w3.org/ns/widgets" id="${nativeConfig.appId}" version="1.0.0">
  <name>${nativeConfig.appName}</name>
  <description>Privacy-first local media anonymizer.</description>
  <author email="web3privacynow@protonmail.com">Web3Privacy Now</author>
  <content src="index.html" />
  <access origin="*" />
</widget>
`,
)
ensureIosSpmVendorFrameworks()

ensureAndroidCordovaModule()
mkdirSync(androidAssetsDir, { recursive: true })
syncPublicAssets(androidPublicDir)
writeFileSync(androidConfigPath, `${JSON.stringify(nativeConfig, null, 2)}\n`)
writeFileSync(androidPluginsPath, '[]\n')

console.log(`Synced ${distDir} -> ${iosPublicDir}`)
console.log(`Synced ${distDir} -> ${androidPublicDir}`)
